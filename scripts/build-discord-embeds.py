#!/usr/bin/env python3
"""Write each page's Discord link preview (a component embed) into its <head>.

Run from anywhere: python scripts/build-discord-embeds.py   (add --check to only report stale pages)
This is a static site, so the preview is a pre-built
<script id="discord:component-embed" type="application/json"> block committed in each page. Every
HTML page except 404.html gets one; a page's title and description come from its own <title> and
<meta name="description">, so re-run this after changing either (build-sitemap.py runs it too,
where the site has one). A preview over Discord's 3,000-byte limit is left out (an HTML comment
instead), and Discord falls back to the page's title and description.
Spec: https://docs.discord.com/developers/link-previews/component-embeds

Copyright (c) Stux.Group. All Rights Reserved.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://" + (ROOT / "CNAME").read_text(encoding="utf-8").strip()

MAX_BYTES = 3000
SITE_NAME = "Stux.Digital"
SITE_COLOUR = "#38bdf8"  # the pages' accent
ICON_URL = "https://global.media.stux.digital/icon.png"
HOME_NOTE = "From idea to online. The idea is planned and the design is done; this site is being built and launching soon."
HOME_LINKS = [("Stux.Digital", "https://stux.digital"), ("Clients", "https://clients.stux.digital")]  # (label, URL) buttons on the coming-soon page
NO_EMBED = {"404.html"}  # error pages get no preview

COMMENT = "<!-- Discord: a custom link preview, generated by scripts/build-discord-embeds.py -->"
BLOCK = re.compile(r"[ \t]*" + re.escape(COMMENT) + r"\n[ \t]*(?:<script id=\"discord:component-embed\"[^\n]*</script>|<!-- discord:component-embed [^\n]*-->)\n")


def discord_md(s: str) -> str:
    """Escapes Discord markdown so data (titles, descriptions) shows as plain text."""
    # Inline formatting, link brackets and backslashes anywhere; headings, quotes and lists only at a line start.
    s = re.sub(r"([\\*_~`|\[\]])", r"\\\1", s)
    return re.sub(r"^([#>-])", r"\\\1", s, flags=re.M)


def text(markdown: str) -> dict:
    return {"type": 10, "content": markdown}


def buttons(links: list) -> dict:
    """A row of link buttons from (label, absolute URL) pairs."""
    return {"type": 1, "components": [{"type": 2, "style": 5, "label": label[:80], "url": url} for label, url in links]}


def section(markdown: str) -> dict:
    """Text with the site's icon beside it."""
    return {"type": 9, "components": [text(markdown)], "accessory": {"type": 11, "media": {"url": ICON_URL}}}


def payload(components: list, accent: str = SITE_COLOUR):
    """The encoded JSON, or None when it's over Discord's 3,000-byte limit."""
    data = {"component": {"type": 17, "accent_color": int(accent.lstrip("#"), 16), "components": components}}
    encoded = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    encoded = encoded.replace("</", "<\\/")  # can't close the <script> early
    return None if len(encoded.encode("utf-8")) > MAX_BYTES else encoded


def embed(components: list, accent: str = SITE_COLOUR) -> str:
    """The <script> tag, or a comment when it would be over the limit."""
    encoded = payload(components, accent)
    if encoded is None:
        return f"<!-- discord:component-embed left out: over {MAX_BYTES} bytes -->"
    return f'<script id="discord:component-embed" type="application/json">{encoded}</script>'


def abs_url(path: str) -> str:
    return BASE_URL + path


def site_label() -> str:
    """The small site-name line above a page's title, like a normal preview's site name."""
    return f"-# [{discord_md(SITE_NAME)}]({abs_url('/')})\n"


def home_embed() -> str:
    """The coming-soon page: what it is, and where to go in the meantime."""
    return embed([
        section(f"# [{discord_md(SITE_NAME)}]({abs_url('/')})\n**Coming soon**\n{discord_md(HOME_NOTE)}"),
        buttons(HOME_LINKS),
    ])


def legal_embed(title: str, desc: str, url: str, subpages: list) -> str:
    """The legal hub: what it covers, with every legal page as a link."""
    links = " · ".join(f"[{discord_md(label)}]({abs_url(path)})" for path, label in subpages)
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        text(links),
        buttons([("Open", url), ("Home", abs_url("/"))]),
    ])


def page_embed(title: str, desc: str, url: str, back=None) -> str:
    """Any other page: its name and description, with a way back."""
    return embed([
        section(site_label() + f"## [{discord_md(title)}]({url})\n{discord_md(desc)}"),
        buttons([("Open", url), back or ("Home", abs_url("/"))]),
    ])


def head_text(page: str, pattern: str) -> str:
    m = re.search(pattern, page[:page.index("</head>")])
    return html.unescape(m.group(1)) if m else ""


def page_path(rel: str) -> str:
    """The URL path a source file is served at (GitHub Pages drops .html and index.html)."""
    if rel == "index.html":
        return "/"
    if rel.endswith("/index.html"):
        return "/" + rel[:-len("index.html")]
    return "/" + rel[:-len(".html")]


def page_label(rel: str, page: str) -> str:
    """A page's short name: the legal hub is Boring Legal Stuff, otherwise the start of its <title>."""
    if rel == "index.html":
        return "Home"
    if rel == "legal.html":
        return "Boring Legal Stuff"
    return re.split(r" [|—·-] ", head_text(page, r"<title>([^<]*)</title>"))[0].strip()


def pages() -> list:
    """(path, source file, label) for every page that gets a preview: all HTML with a <head>, but the error pages."""
    found = []
    for file in sorted(ROOT.rglob("*.html")):
        rel = file.relative_to(ROOT).as_posix()
        if ".git" in file.parts or "node_modules" in file.parts or rel in NO_EMBED:
            continue
        page = file.read_text(encoding="utf-8")
        if "<head" in page:
            found.append((page_path(rel), rel, page_label(rel, page)))
    return found


def embed_for(path: str, label: str, page: str) -> str:
    desc = head_text(page, r'<meta name="description" content="([^"]*)"')
    url = abs_url(path)
    if path == "/":
        return home_embed()
    if path == "/legal":
        subpages = [(p, lbl) for p, _src, lbl in pages() if p.startswith("/legal/")]
        return legal_embed(label, desc, url, subpages)
    if path.startswith("/legal/"):
        return page_embed(label, desc, url, ("Boring Legal Stuff", abs_url("/legal")))
    return page_embed(label, desc, url)


def with_embed(page: str, tag: str) -> str:
    """The page with its embed block replaced, or added after the meta description."""
    m = re.search(r'\n([ \t]*)<meta name="description"[^\n]*\n', page)
    indent = m.group(1) if m else "    "
    block = f"{indent}{COMMENT}\n{indent}{tag}\n"
    if BLOCK.search(page):
        return BLOCK.sub(lambda _m: block, page, count=1)
    if not m:
        raise SystemExit("no <meta name=\"description\"> to put the embed after")
    return page[:m.end()] + block + page[m.end():]


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    stale = []
    listing = pages()
    for path, src, label in listing:
        file = ROOT / src
        page = file.read_text(encoding="utf-8")
        updated = with_embed(page, embed_for(path, label, page))
        if updated != page:
            stale.append(src)
            if not check:
                file.write_text(updated, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Discord embeds out of date (run python scripts/build-discord-embeds.py): " + ", ".join(stale))
            return 1
        print(f"Discord embeds up to date ({len(listing)} pages)")
        return 0
    print(f"Wrote Discord embeds: {len(stale)} of {len(listing)} pages changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
